#!/usr/bin/env bash
# Bounded PRACH-delay measurement mode.
#
#   make BENCH=1 PROFILE=bench-20mhz prach-timing SECS=120
#
# This is deliberately separate from the normal bench profile: the committed
# protoru.yml stays at log.level info. The mode materialises a debug overlay in
# build/local-profiles/ (gitignored), runs `smoke-fh` for a bounded interval and
# collects the RU log. It is a measurement mode, not a soak: at debug the RU
# emulator logs every OFH packing step and grows by ~29 GB/h.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PROFILE="${PROFILE:-bench-20mhz}"
SECS="${SECS:-120}"

if [[ "${BENCH:-0}" != "1" ]]; then
  echo "prach-timing: FAIL: this mode is bench-only; run with BENCH=1" >&2
  exit 2
fi
if ! [[ "$SECS" =~ ^[0-9]+$ ]] || ((SECS < 10 || SECS > 120)); then
  echo "prach-timing: FAIL: SECS must be an integer in 10..120 (bounded run)" >&2
  exit 2
fi
SRC="profiles/$PROFILE/protoru.yml"
[[ -f "$SRC" ]] || { echo "prach-timing: FAIL: missing $SRC" >&2; exit 2; }
[[ -f "profiles/$PROFILE/du-fh.yml" ]] || { echo "prach-timing: FAIL: missing profiles/$PROFILE/du-fh.yml" >&2; exit 2; }

OUT="build/local-profiles/$PROFILE/protoru-prach-timing.yml"
python3 - "$SRC" "$OUT" <<'PY'
import pathlib, re, sys
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
text = src.read_text()
lines = text.splitlines(keepends=True)
in_log = False
changed = False
for i, line in enumerate(lines):
    if line.startswith("log:"):
        in_log = True
        continue
    if in_log and re.match(r"^\s+level:", line):
        lines[i] = re.sub(r"(level:)\s*\S+", r"\1 debug", line)
        changed = True
        break
if not changed:
    sys.exit(f"prach-timing: no log.level line in {src}")
header = (
    "# Generated by scripts/prach_timing_run.sh -- bounded PRACH-delay "
    "measurement overlay.\n"
    "# Gitignored and never used by the normal bench profile (which stays at "
    "log.level info).\n"
)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header + "".join(lines))
PY

hours_gb="$(python3 -c "print(f'{$SECS * 29.0 / 3600.0:.2f}')")"
echo "[prach-timing] bounded measurement mode: ${SECS}s, profile ${PROFILE}, UHD"
echo "[prach-timing] overlay: ${OUT} (log.level debug; generated, gitignored)"
echo "[prach-timing] expected log growth: ~29 GB/h at debug -> ~${hours_gb} GB for ${SECS}s"
echo "[prach-timing] rate measured on the null-radio gate, dominated by RU_EMU OFH debug; UHD expected similar per-slot [UNVERIFIED]"
echo "[prach-timing] normal bench profiles remain at log.level info; do not use this mode for a soak"

if [[ "${DRY_RUN:-0}" == "1" ]]; then
  echo "[prach-timing] DRY_RUN=1: overlay generated; not starting the stack"
  exit 0
fi

set +e
SECS="$SECS" PROFILE="$PROFILE" PROTORU_PROFILE=uhd \
  timeout $((SECS + 240)) make -C "$ROOT" BENCH=1 PROFILE="$PROFILE" PROTORU_PROFILE=uhd \
  SMOKE_SECS="$SECS" PROTORU_YML_OVERRIDE="$ROOT/$OUT" smoke-fh
rc=$?
set -e

LOG="$ROOT/docs/reports/raw/smoke-fh-ru.log"
if [[ -f "$LOG" ]]; then
  echo "[prach-timing] collected log: ${LOG}"
  ls -lh "$LOG" | awk '{print "  size:", $5}'
  printf '  PRACH window complete: %s\n' "$(grep -c 'PRACH window complete' "$LOG" 2>/dev/null || echo 0)"
  printf '  PRACH U-plane send:    %s\n' "$(grep -c 'PRACH U-plane send' "$LOG" 2>/dev/null || echo 0)"
  echo "  parse: grep 'PRACH window complete\\|PRACH U-plane send' ${LOG}"
fi
exit "$rc"
