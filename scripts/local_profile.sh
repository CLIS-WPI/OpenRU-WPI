#!/usr/bin/env bash
# Materialise a local copy of a bench profile and patch tx_gain / reference.
#
#   scripts/local_profile.sh <profile> <tx_gain|-> [external|internal|-]
#
# Prints the ABSOLUTE path of the generated protoru.yml. The committed profile
# is never modified: the copy lives under gitignored build/local-profiles/.
# Used by `make up` and `make restart-ru`.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROFILE="${1:?usage: local_profile.sh <profile> <tx_gain|-> [external|internal|-]}"
TX_GAIN="${2:--}"
REF="${3:--}"

SRC="$ROOT/profiles/$PROFILE/protoru.yml"
OUT="$ROOT/build/local-profiles/$PROFILE/protoru.yml"
[[ -f "$SRC" ]] || { echo "local_profile: missing $SRC" >&2; exit 1; }

python3 - "$SRC" "$OUT" "$TX_GAIN" "$REF" <<'PY'
import os
import pathlib
import re
import sys

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
tx_raw, ref = sys.argv[3], sys.argv[4]

tx = None
if tx_raw not in ("", "-"):
    try:
        tx = float(tx_raw)
    except ValueError:
        sys.exit(f"local_profile: TX_GAIN={tx_raw!r} is not a number")
    if not (0.0 <= tx <= 65.0) or abs(tx * 2 - round(tx * 2)) > 1e-9:
        sys.exit(f"local_profile: TX_GAIN={tx:g} outside 0..65 dB or off the 0.5 dB step")

if ref in ("", "-"):
    ref = None
elif ref not in ("external", "internal"):
    sys.exit(f"local_profile: REF={ref!r} must be external or internal")

addr, mgmt = os.environ.get("BENCH_USRP_ADDR", ""), os.environ.get("BENCH_MGMT_ADDR", "")
if tx is None and ref is None and not addr:
    sys.exit("local_profile: set TX_GAIN, REF and/or BENCH_USRP_ADDR")

text = src.read_text()

if addr:
    # Device address of the selected bench radio (BENCH_RADIO -> docker/radios/<radio>.env).
    text, n = re.subn(r"(?m)^(\s*device_args:.*?)(?<![a-z_])addr=[^,\"]+", lambda m: f"{m.group(1)}addr={addr}", text, count=1)
    if n != 1:
        sys.exit(f"local_profile: no device_args addr field in {src}")
    if mgmt:
        text, n = re.subn(r"(?m)^(\s*device_args:.*?)mgmt_addr=[^,\"]+", lambda m: f"{m.group(1)}mgmt_addr={mgmt}", text, count=1)
        if n != 1:
            sys.exit(f"local_profile: no device_args mgmt_addr field in {src}")

if tx is not None:
    text, n = re.subn(
        r"(?m)^(\s*)tx_gain:\s*\S+",
        lambda m: f"{m.group(1)}tx_gain: {tx:g}",
        text,
        count=1,
    )
    if n != 1:
        sys.exit(f"local_profile: no tx_gain line in {src}")

if ref is not None:
    # REF=external selects only the 10 MHz frequency reference. Time stays
    # internal: set_time_unknown_pps() at the next PPS would reset the radio
    # time and break ProtO-RU's wall-clock slot alignment.
    time_ref = "internal"
    text, n = re.subn(
        r"(?m)^(\s*device_args:.*?)clock_source=[^,]+",
        lambda m: f"{m.group(1)}clock_source={ref}",
        text,
        count=1,
    )
    if n != 1:
        sys.exit(f"local_profile: no device_args clock_source field in {src}")
    text, n = re.subn(
        r"(?m)^(\s*device_args:.*?)time_source=[^,]+",
        lambda m: f"{m.group(1)}time_source={time_ref}",
        text,
        count=1,
    )
    if n != 1:
        sys.exit(f"local_profile: no device_args time_source field in {src}")
    text, n = re.subn(
        r"(?m)^(\s*)clock_source:\s*\S+",
        lambda m: f"{m.group(1)}clock_source: {ref}",
        text,
        count=1,
    )
    if n != 1:
        sys.exit(f"local_profile: no YAML clock_source field in {src}")
    text, n = re.subn(
        r"(?m)^(\s*)sync_source:\s*\S+",
        lambda m: f"{m.group(1)}sync_source: {time_ref}",
        text,
        count=1,
    )
    if n != 1:
        sys.exit(f"local_profile: no YAML sync_source field in {src}")

tx_label = "-" if tx is None else f"{tx:g}"
ref_label = ref or "-"
ref_note = {
    "external": " (10 MHz only; time internal)",
    "internal": " (N310 clock/time)",
}.get(ref, "")
header = (
    "# Generated by scripts/local_profile.sh -- gitignored local overlay.\n"
    f"# tx_gain={tx_label} ref={ref_label}{ref_note} radio={os.environ.get('BENCH_RADIO', '-')} addr={addr or '-'}\n"
)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header + text)
print(f"local_profile: {out} tx_gain={tx_label} ref={ref_label}")
PY
echo "$OUT"
